def _host_origins(hosts):
    origins = []
    for host in hosts:
        host = host.strip()
        if not host or host == "*" or host.startswith("["):
            continue
        if host.startswith("."):
            host = host[1:]
        if "://" in host:
            origins.append(host.rstrip("/"))
            continue
        origins.append(f"https://{host}")
        origins.append(f"http://{host}")
    return origins


